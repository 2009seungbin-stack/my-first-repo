"""Download and independently decode 24 PNG resize results from a specified site.

Run after starting a local server, or use a frozen deployment:
  python tools/editorial/measure-resize-dimensions.py --base URL --expected-sha COMMIT
Outputs default to test-results; published evidence cannot be overwritten.
The diagnostic input is generated by this script and uses no third-party image.
"""
import argparse,hashlib,json
from datetime import datetime,timezone
from pathlib import Path
from PIL import Image,__version__ as pillow_version
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--base',required=True);parser.add_argument('--expected-sha');parser.add_argument('--output',type=Path)
args=parser.parse_args();BASE=args.base.rstrip('/')
if not BASE.startswith(('http://','https://')):parser.error('base must be an HTTP(S) site URL')
OUT=(args.output or ROOT/'test-results'/'editorial-resize-dimensions').resolve()
if OUT.is_relative_to(ROOT/'assets') and OUT.exists():parser.error('Record measurements outside existing published assets')
OUT.mkdir(parents=True,exist_ok=True)
source=OUT/'authored-32x24.png';image=Image.new('RGBA',(32,24));image.putdata([((x*17)%256,(y*23)%256,(x*7+y*13)%256,255) for y in range(24) for x in range(32)]);image.save(source);image.close()
def sha(raw):return hashlib.sha256(raw).hexdigest()
rows=[];browsers=[];errors=[];versions=[]
with sync_playwright() as p:
 for engine in ['chromium','firefox']:
  browser=getattr(p,engine).launch();ctx=browser.new_context(accept_downloads=True);page=ctx.new_page();page.on('pageerror',lambda error:errors.append(str(error)))
  def version():
   response=ctx.request.get(BASE+'/build.txt');assert response.status==200
   value=response.text().strip()
   if args.expected_sha:assert value==args.expected_sha,(value,args.expected_sha)
   return value
  before=version();browsers.append({'engine':engine,'version':browser.version});app=ctx.request.get(BASE+'/src/task/resize.js');assert app.status==200
  for mode in ['contain','cover','stretch']:
   for allow in [False,True]:
    for w,h in [(128,96),(128,128)]:
     response=page.goto(f'{BASE}/en/image/resize/?w={w}&h={h}&fit={mode}&enlarge={int(allow)}',wait_until='networkidle');assert response.status in [200,304]
     assert page.evaluate('!window.__priorMeasurementDocument'),'navigation must create a new document'
     page.wait_for_selector('#fileInput',state='attached');page.locator('#fileInput').set_input_files(source)
     page.wait_for_function('()=>document.querySelector("#taskDownload")&&!document.querySelector("#taskDownload").disabled')
     assert page.locator('#resizeNoEnlarge').is_checked()==(not allow)
     name=f'{engine}-{mode}-{w}x{h}-allow{int(allow)}.png';target=OUT/name
     with page.expect_download() as event:page.locator('#taskDownload').click()
     event.value.save_as(target)
     with Image.open(target) as decoded:
      decoded.load();expected=(w,h) if allow else ((32,24) if h==96 else (24,24))
      assert decoded.format=='PNG' and decoded.size==expected,(name,decoded.format,decoded.size,expected)
      rgba=decoded.convert('RGBA');bbox=rgba.getchannel('A').getbbox();pixels=sha(rgba.tobytes());rgba.close()
     rows.append({'browser':engine,'mode':mode,'requested':[w,h],'neverEnlarge':not allow,'file':name,'decodedSize':list(expected),'format':'PNG','bytes':target.stat().st_size,'sha256':sha(target.read_bytes()),'rgbaSHA256':pixels,'alphaBounds':list(bbox) if bbox else None,'note':page.locator('#viewerNote').inner_text()})
     page.evaluate('window.__priorMeasurementDocument=true')
  after=version();assert before==after;versions.append({'browser':engine,'before':before,'after':after,'resizeModuleSHA256':sha(app.body())});ctx.close();browser.close()
assert not errors,errors
report={'measuredAt':datetime.now(timezone.utc).isoformat(),'base':BASE,'expectedCommit':args.expected_sha,'input':{'file':source.name,'size':[32,24],'sha256':sha(source.read_bytes()),'provenance':'Generated diagnostic pattern; no third-party image'},'browsers':browsers,'pillow':pillow_version,'siteVersions':versions,'downloads':rows,'pageErrors':errors,'scope':'Dimensions and decoded alpha bounds of downloaded PNG files; no visual-quality or file-size-reduction guarantee.'}
(OUT/'measurements.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Passed {len(rows)} actual PNG downloads in two browser engines; output: {OUT}')
