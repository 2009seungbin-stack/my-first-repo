// Copies the engine-side helper files the UI workspace ships (tools/engine-verify/ui/helpers/*, the
// exact files the engine verifiers run) into src/game/ui/export/helper-sources.js, so the browser
// exporter embeds them verbatim. tests/studio-ui-export.test.mjs fails when the two drift apart.
//   node tools/ui-helpers-embed.mjs
import {readFile,writeFile} from 'node:fs/promises';
import {existsSync} from 'node:fs';
const dir=new URL('./engine-verify/ui/helpers/',import.meta.url);
export const HELPERS=Object.freeze({
 GODOT_UI_HELPER:'nerulio_ui_import.gd',
 UNITY_UI_IMPORTER:'NerulioUIImporter.cs',
 GODOT_FONT_HELPER:'nerulio_font_import.gd',
 UNITY_TMP_IMPORTER:'NerulioTMPFontImporter.cs'
});
export async function helperSources(){
 const out={};
 for(const [k,f] of Object.entries(HELPERS)){const u=new URL(f,dir);out[k]=existsSync(u)?(await readFile(u,'utf8')).replace(/\r\n/g,'\n'):'';}
 return out;
}
if(import.meta.url===`file:///${process.argv[1].replace(/\\/g,'/').replace(/^\//,'')}`||process.argv[1]?.endsWith('ui-helpers-embed.mjs')){
 const src=await helperSources();
 const body=Object.entries(src).map(([k,v])=>`export const ${k}=${JSON.stringify(v)};`).join('\n');
 await writeFile(new URL('../src/game/ui/export/helper-sources.js',import.meta.url),`/** GENERATED by tools/ui-helpers-embed.mjs from tools/engine-verify/ui/helpers/ — do not edit by hand.\n * These are the exact helper files the engine verifiers ran (see docs/STUDIO-UI.md). */\n${body}\n`);
 console.log('helper-sources.js:',Object.entries(src).map(([k,v])=>`${k} ${v.length} chars`).join(', '));
}
