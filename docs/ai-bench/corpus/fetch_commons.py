"""Sample public-domain / CC0 AI-generated images from Wikimedia Commons by category.
Usage: python fetch_commons.py <corpus-dir> [--list-only]
Only files whose Commons licence metadata says public domain or CC0 are kept (most AI outputs carry
{{PD-algorithm}}). Writes images/wc-<kind>-<n>.<ext> and _src/commons-picked.json."""
import sys,json,hashlib,random,re,time
from pathlib import Path
import requests
ROOT=Path(sys.argv[1]);SRC=ROOT/'_src';IMG=ROOT/'images';SRC.mkdir(exist_ok=True,parents=True);IMG.mkdir(exist_ok=True)
S=requests.Session();S.headers['User-Agent']='nerulio-ai-bench/1.0 (https://nerulio.com; seungbinbugae@gmail.com) corpus builder'
API='https://commons.wikimedia.org/w/api.php'
# kind -> (categories, how many). Over-sampled: a visual screen drops unsuitable files afterwards.
KINDS={
 'chatgpt':(['Images generated by ChatGPT','GPT Image'],22),
 'gemini':(['Images generated by Gemini','Images generated by Nano Banana'],18),
 'midjourney':(['Images generated by Midjourney'],16),
 'sdxl':(['Images generated by Stable Diffusion'],12),
 'flux':(['Images generated by Flux (text-to-image model)'],10),
 'dalle':(['Images generated by DALL-E'],10),
 'pixel':(['AI-generated pixel art'],30),
 'icon':(['AI-generated icons','AI-generated pictograms'],12),
 'character':(['AI-generated fictional characters','AI-generated manga illustrations'],16),
 'portrait':(['AI-generated portraits'],12),
}
BAD=re.compile(r'erotic|nude|nsfw|sexual|porn|violence|gore|politic|propaganda|trump|biden|putin|hitler|nazi|war\b|deepfake',re.I)
def members(cat,limit=400):
    out=[];cont={}
    while len(out)<limit:
        p={'action':'query','format':'json','generator':'categorymembers','gcmtitle':'Category:'+cat,'gcmtype':'file','gcmlimit':'100',
           'prop':'imageinfo|categories','iiprop':'url|size|mime|sha1|extmetadata','iiextmetadatafilter':'LicenseShortName|License|UsageTerms|Artist|Credit|ImageDescription','cllimit':'max',**cont}
        d=S.get(API,params=p,timeout=60).json()
        for pg in d.get('query',{}).get('pages',{}).values():
            if 'imageinfo' in pg:out.append(pg)
        if 'continue' not in d:break
        cont=d['continue'];time.sleep(.2)
    return out
def ok(pg):
    ii=pg['imageinfo'][0];m=ii.get('extmetadata',{})
    lic=(m.get('LicenseShortName',{}).get('value','')+' '+m.get('License',{}).get('value','')).lower()
    cats=' '.join(c['title'] for c in pg.get('categories',[]))
    if not ('public domain' in lic or lic.strip().startswith('pd') or ' pd' in lic or 'cc0' in lic):return None
    if ii['mime'] not in ('image/png','image/jpeg','image/webp'):return None
    if min(ii['width'],ii['height'])<400 or ii['width']*ii['height']>9e6:return None
    if BAD.search(pg['title']+' '+cats):return None
    return lic
rng=random.Random(20261011);picked=[];seen=set()
for kind,(cats,n) in KINDS.items():
    pool=[]
    for c in cats:
        for pg in members(c):
            lic=ok(pg)
            if lic and pg['title'] not in seen:pool.append((pg,lic))
    rng.shuffle(pool);k=0
    print(kind,'pool',len(pool),flush=True)
    for pg,lic in pool:
        if k>=n:break
        seen.add(pg['title']);ii=pg['imageinfo'][0];m=ii['extmetadata'];k+=1
        ext={'image/png':'png','image/jpeg':'jpg','image/webp':'webp'}[ii['mime']]
        rid=f'wc-{kind}-{k:02d}';picked.append({'id':rid,'file':f'{rid}.{ext}','kind_hint':kind,'source':'Wikimedia Commons','title':pg['title'],
          'url':ii['descriptionurl'],'download':ii['url'],'license':m.get('LicenseShortName',{}).get('value',''),'license_detail':lic,
          'artist':re.sub('<[^>]+>','',m.get('Artist',{}).get('value',''))[:200],'description':re.sub('<[^>]+>','',m.get('ImageDescription',{}).get('value',''))[:400],
          'width':ii['width'],'height':ii['height'],'commons_sha1':ii['sha1']})
if '--list-only' in sys.argv:
    print(json.dumps(picked,indent=1,ensure_ascii=False));sys.exit()
for r in picked:
    for attempt in range(4):
        resp=S.get(r['download'],timeout=120)
        if resp.status_code==200:break
        time.sleep(5*(attempt+1))
    resp.raise_for_status();data=resp.content
    assert hashlib.sha1(data).hexdigest()==r['commons_sha1'],r['id']
    (IMG/r['file']).write_bytes(data);r['sha256']=hashlib.sha256(data).hexdigest();print(r['id'],len(data),flush=True);time.sleep(.5)
(SRC/'commons-picked.json').write_text(json.dumps(picked,indent=1,ensure_ascii=False),encoding='utf-8')
